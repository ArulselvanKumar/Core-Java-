package for_Loop;

public class Task2 {

	public static void main(String[] args) {
		// 3.Print all Even numbers between 1 and 50
		int i=1;
		for(i=1; i<=50;i++) {
			if(i%2==0) {
				System.out.println(i);
			}
			
		}
		
		//4. Print all odd numbers between 1 and 50
		int j=1;
		for(j=1; j<=50;j++) {
			if(j%2!=0) {
				System.out.println(j);
			}
	}

	}
}
