package for_Loop;

public class Task1 {

	public static void main(String[] args) {
		// 1. print numbers from 1 to 100
		
		int i=1;
		for(i=1; i<=100;i++) {
			System.out.println(i);
		}
		
		// 2. print numbers from 100 to 1
		
		int j=100;
		for(j=100;j>=1; j--) {
			System.out.println(j);

		}
	}
	     
}
