package nested_Loop;

public class Task3 {

	public static void main(String[] args) {
		// 3. Print a square pattern
          for(int i=1; i<=4;i++) {
        	  for(int j=1;j<=4;j++) {
        		  System.out.print("*");
        	  }
        	  System.out.println();
          }

	}

}
